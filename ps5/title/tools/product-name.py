#!/usr/bin/env python3
"""Generate the native display-name constant from canonical title metadata."""
import json
from pathlib import Path

ps5 = Path(__file__).resolve().parents[2]
param = json.loads((ps5 / 'title/sce_sys/param.json').read_text())
localized = param['localizedParameters']
name = localized[localized['defaultLanguage']]['titleName']
output = ps5 / 'include/product-name.h'
text = ('/* Generated by title/tools/product-name.py from sce_sys/param.json. */\n'
        '#ifndef PS5_PRODUCT_NAME_H\n#define PS5_PRODUCT_NAME_H\n'
        f'#define PRODUCT_DISPLAY_NAME {json.dumps(name)}\n#endif\n')
if not output.exists() or output.read_text() != text:
    output.write_text(text)
